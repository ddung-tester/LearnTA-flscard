  source VARCHAR(20) NOT NULL,
  section VARCHAR(80) NOT NULL,
  type VARCHAR(20) NOT NULL CHECK (type IN ('multiple_choice', 'fill_blank')),
  instruction TEXT NULL,
  prompt TEXT NOT NULL,
  -- Trắc nghiệm: [{ key, text }] và chữ cái đáp án đúng. Điền từ: các cách viết được chấp nhận.
  options JSONB NULL,
  answer_key VARCHAR(4) NULL,
  accepted_answers JSONB NULL,
  explanation TEXT NULL,
  answer_source VARCHAR(60) NULL,
  image_description VARCHAR(500) NULL,
  -- Bài nghe: file audio private (<slug khoá>/<audio_path>) hoặc lời thoại cho trình duyệt đọc
  audio_path VARCHAR(255) NULL,
  listen_text TEXT NULL,
  sort_order INTEGER NOT NULL DEFAULT 0,

  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,

  CONSTRAINT unique_course_questions_key UNIQUE (lesson_id, question_key)
);
CREATE INDEX IF NOT EXISTS idx_course_questions_order ON course_questions (lesson_id, sort_order);

