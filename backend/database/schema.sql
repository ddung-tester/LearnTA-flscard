-- Schema PostgreSQL (Supabase). Gộp đủ migration MySQL 001..016 (bản cũ ở mysql-legacy/).
-- Chạy trên DB trống: psql "$DATABASE_URL" -f database/schema.sql

-- Thay cho ON UPDATE CURRENT_TIMESTAMP của MySQL
CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger AS $$
BEGIN
  NEW.updated_at = CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TABLE IF NOT EXISTS users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fullname VARCHAR(50) NOT NULL,
  email VARCHAR(255) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NULL,
  google_id VARCHAR(255) NULL UNIQUE,
  avatar_url VARCHAR(512),

  total_xp INTEGER NOT NULL DEFAULT 0 CHECK (total_xp >= 0),
  current_streak INTEGER NOT NULL DEFAULT 0 CHECK (current_streak >= 0),
  longest_streak INTEGER NOT NULL DEFAULT 0 CHECK (longest_streak >= 0),
  last_study_date DATE,

  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS decks (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NULL REFERENCES users(id) ON DELETE SET NULL,

  title VARCHAR(255) NOT NULL,
  description TEXT,

  icon VARCHAR(80),
  theme_color VARCHAR(50),
  is_public BOOLEAN NOT NULL DEFAULT FALSE,

  streak INTEGER NOT NULL DEFAULT 0 CHECK (streak >= 0),
  mastered_count INTEGER NOT NULL DEFAULT 0 CHECK (mastered_count >= 0),

  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,

  CONSTRAINT unique_user_deck_title UNIQUE (user_id, title)
);
CREATE INDEX IF NOT EXISTS idx_decks_user_id ON decks (user_id);

CREATE TABLE IF NOT EXISTS cards (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  deck_id BIGINT NOT NULL REFERENCES decks(id) ON DELETE CASCADE,

  term_en VARCHAR(255) NOT NULL,
  meaning_vi VARCHAR(255) NOT NULL,
  example_sentence TEXT,
  example_translation TEXT,
  note TEXT,

  pronunciation VARCHAR(255),
  part_of_speech VARCHAR(50),
  -- Câu mẫu 6 thì do AI sinh (seed-ai-examples.js)
  tense_examples JSONB NULL DEFAULT NULL,

  is_favorite BOOLEAN NOT NULL DEFAULT FALSE,
  sort_order INTEGER NOT NULL DEFAULT 0 CHECK (sort_order >= 0),

  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_cards_deck_id ON cards (deck_id);
CREATE INDEX IF NOT EXISTS idx_cards_sort_order ON cards (deck_id, sort_order);
CREATE INDEX IF NOT EXISTS idx_cards_created_at ON cards (created_at);

CREATE TABLE IF NOT EXISTS study_sessions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NULL REFERENCES users(id) ON DELETE SET NULL,
  client_request_id VARCHAR(80) NULL,
  request_hash CHAR(64) NULL,
  deck_id BIGINT NOT NULL REFERENCES decks(id) ON DELETE CASCADE,

  mode VARCHAR(20) NOT NULL CHECK (mode IN (
    'flashcard', 'quiz', 'written', 'review',
    'listening', 'context', 'matching', 'mixed'
  )),
  direction VARCHAR(5) NOT NULL CHECK (direction IN ('en-vi', 'vi-en')),

  only_favorite BOOLEAN NOT NULL DEFAULT FALSE,
  random_order BOOLEAN NOT NULL DEFAULT FALSE,

  started_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  ended_at TIMESTAMPTZ NULL,
  duration_seconds INTEGER NOT NULL DEFAULT 0 CHECK (duration_seconds >= 0),

  total INTEGER NOT NULL DEFAULT 0 CHECK (total >= 0),
  correct INTEGER NOT NULL DEFAULT 0 CHECK (correct >= 0),
  review INTEGER NOT NULL DEFAULT 0 CHECK (review >= 0),
  xp_earned INTEGER NOT NULL DEFAULT 0 CHECK (xp_earned >= 0),
  max_combo INTEGER NOT NULL DEFAULT 0 CHECK (max_combo >= 0),
  segment_size INTEGER NOT NULL DEFAULT 0 CHECK (segment_size >= 0),
  segment_total INTEGER NOT NULL DEFAULT 0 CHECK (segment_total >= 0),
  segment_completed INTEGER NOT NULL DEFAULT 0 CHECK (segment_completed >= 0),
  progress_segments JSONB NULL,
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,

  CONSTRAINT uq_study_sessions_user_request UNIQUE (user_id, client_request_id)
);
CREATE INDEX IF NOT EXISTS idx_study_sessions_user_id ON study_sessions (user_id);
CREATE INDEX IF NOT EXISTS idx_study_sessions_deck_id ON study_sessions (deck_id);
CREATE INDEX IF NOT EXISTS idx_study_sessions_user_mode ON study_sessions (user_id, mode);
CREATE INDEX IF NOT EXISTS idx_study_sessions_created ON study_sessions (started_at);

CREATE TABLE IF NOT EXISTS study_answers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
