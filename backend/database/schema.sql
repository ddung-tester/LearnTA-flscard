CREATE TABLE IF NOT EXISTS course_question_progress (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  question_id BIGINT NOT NULL REFERENCES course_questions(id) ON DELETE CASCADE,
  is_correct BOOLEAN NOT NULL,
  mastery_level SMALLINT NOT NULL DEFAULT 0 CHECK (mastery_level >= 0),
  next_review_at TIMESTAMPTZ NULL,

  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,

  CONSTRAINT unique_course_question_progress UNIQUE (user_id, question_id)
);
CREATE INDEX IF NOT EXISTS idx_course_question_progress_due ON course_question_progress (user_id, next_review_at);
CREATE INDEX IF NOT EXISTS idx_course_question_progress_question ON course_question_progress (question_id);

DO $$
DECLARE
  bang TEXT;
BEGIN
  FOREACH bang IN ARRAY ARRAY[
    'users', 'decks', 'cards', 'study_sessions', 'card_progress', 'mistake_words',
    'card_reviews', 'user_settings', 'roadmaps', 'courses', 'course_lessons',
    'course_questions', 'course_question_progress'
  ] LOOP
    EXECUTE format('DROP TRIGGER IF EXISTS trg_%1$s_updated_at ON %1$I', bang);
    EXECUTE format(
      'CREATE TRIGGER trg_%1$s_updated_at BEFORE UPDATE ON %1$I FOR EACH ROW EXECUTE FUNCTION set_updated_at()',
      bang
    );
  END LOOP;
END $$;

-- Backend tự kết nối bằng chuỗi kết nối (không qua API Supabase): chặn API công khai đọc thẳng bảng
DO $$
DECLARE
  bang TEXT;
BEGIN
  FOR bang IN SELECT tablename FROM pg_tables WHERE schemaname = 'public' LOOP
    EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', bang);
  END LOOP;
END $$;
